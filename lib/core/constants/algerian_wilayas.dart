List<String> filterWilayas(String query) {
  final trimmed = query.trim();
  if (trimmed.isEmpty) return List.unmodifiable(algerianWilayas);

  return algerianWilayas.where((wilaya) {
    final withoutAl = wilaya.startsWith('ال') ? wilaya.substring(2) : wilaya;
    return wilaya.contains(trimmed) || withoutAl.contains(trimmed);
  }).toList();
}

bool isValidWilaya(String? value) =>
    value != null && algerianWilayas.contains(value.trim());
